bool spirv_uses_cooperative_matrix(const std::vector<uint32_t>& spirv)
{
    for (size_t i = 5; i < spirv.size();)
    {
        const uint32_t word_count = spirv[i] >> 16;
        const spv::Op opcode = (spv::Op)(spirv[i] & 0xffff);
        if (word_count == 0 || i + word_count > spirv.size())
            return false;

        if (opcode == spv::Op::OpTypeCooperativeMatrixKHR
            || opcode == spv::Op::OpCooperativeMatrixLoadKHR
            || opcode == spv::Op::OpCooperativeMatrixStoreKHR
            || opcode == spv::Op::OpCooperativeMatrixMulAddKHR)
            return true;

        if (opcode == spv::Op::OpCapability && word_count == 2
            && spirv[i + 1] == (uint32_t)spv::Capability::CooperativeMatrixKHR)
            return true;

        i += word_count;
    }

    return false;
}

