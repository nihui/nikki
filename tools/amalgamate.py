import argparse
from pathlib import Path
import sys


PROJECT_ROOT = Path(__file__).resolve().parents[1]
SOURCE_MANIFEST = PROJECT_ROOT / "src" / "source_manifest.txt"
VALID_GROUPS = {"translator", "driver"}


def read_source_manifest(source_manifest=SOURCE_MANIFEST):
    entries = []
    seen = set()
    for line_number, line in enumerate(
        source_manifest.read_text(encoding="utf-8").splitlines(), start=1
    ):
        line = line.strip()
        if not line or line.startswith("#"):
            continue

        fields = line.split(None, 1)
        if len(fields) != 2 or fields[0] not in VALID_GROUPS:
            raise ValueError(
                "invalid source manifest entry at {}:{}".format(
                    source_manifest, line_number
                )
            )

        relative = Path(fields[1])
        if relative.is_absolute() or ".." in relative.parts or not relative.parts:
            raise ValueError(
                "invalid source manifest path at {}:{}: {}".format(
                    source_manifest, line_number, fields[1]
                )
            )
        if relative.parts[0] != "src":
            raise ValueError(
                "source manifest path must be below src at {}:{}: {}".format(
                    source_manifest, line_number, fields[1]
                )
            )
        if relative in seen:
            raise ValueError(
                "duplicate source manifest path at {}:{}: {}".format(
                    source_manifest, line_number, fields[1]
                )
            )
        if not (PROJECT_ROOT / relative).is_file():
            raise ValueError(
                "source manifest file does not exist at {}:{}: {}".format(
                    source_manifest, line_number, fields[1]
                )
            )

        seen.add(relative)
        entries.append((fields[0], relative))

    if not entries:
        raise ValueError("source manifest is empty: {}".format(source_manifest))
    return entries


def module_source(path):
    source = path.read_text(encoding="utf-8")
    if path.name == "entrypoints.cpp":
        proc_table = (PROJECT_ROOT / "src" / "vulkan_procs.inc").read_text(
            encoding="utf-8"
        ).rstrip()
        source = source.replace('#include "vulkan_procs.inc"', proc_table)
    if path.name == "vulkan_procs.inc":
        return ""
    source = source.replace('#include "common.h"\n', "")
    source = source.replace('#include "../common.h"\n', "")
    source = source.replace('#include "vulkan_internal.h"\n', "")
    source = source.replace('#include "abi_guard.h"\n', "")
    source = source.replace('#include "../vulkan_internal.h"\n', "")
    source = source.replace('#include "../translator/translator_internal.h"\n', "")
    source = source.replace('#include "backend/device_profile.h"\n', "")
    source = source.replace('#include "backend/objects.h"\n', "")
    source = source.replace('#include "backend/device.h"\n', "")
    source = source.replace('#include "backend/runtime.h"\n', "")
    source = source.replace('#include "backend/dispatch.h"\n', "")
    source = source.replace('#include "backend/shader_module.h"\n', "")
    source = source.replace('#include "device_profile.h"\n', "")
    source = source.replace('#include "objects.h"\n', "")
    source = source.replace('#include "device.h"\n', "")
    source = source.replace('#include "runtime.h"\n', "")
    source = source.replace('#include "dispatch.h"\n', "")
    source = source.replace('#include "shader_module.h"\n', "")
    source = source.replace('#include "translator/translator_internal.h"\n', "")
    source = source.replace('#include "translator_internal.h"\n', "")
    source = source.replace('#include "translator_stages.h"\n', "")
    return source.rstrip()


def amalgamation(source_manifest=SOURCE_MANIFEST):
    parts = [
        "// Generated by tools/amalgamate.py. Do not edit this file directly.\n"
        "// Copyright 2026 nihui\n"
        "// SPDX-License-Identifier: Apache-2.0",
        "// Edit src/ and regenerate the amalgamation instead.",
    ]
    for _, relative in read_source_manifest(source_manifest):
        path = PROJECT_ROOT / relative
        relative_path = relative.as_posix()
        parts.append("// begin " + relative_path + "\n\n" + module_source(path)
                     + "\n\n// end " + relative_path)
    return "\n\n".join(parts) + "\n"


def main():
    parser = argparse.ArgumentParser(description="Generate the nikki single-source distribution.")
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--output", type=Path, help="path to the generated nikki.cpp")
    group.add_argument("--check", type=Path, help="check an existing generated nikki.cpp")
    group.add_argument("--stdout", action="store_true", help="write the generated source to stdout")
    parser.add_argument(
        "--manifest",
        type=Path,
        default=SOURCE_MANIFEST,
        help="source manifest to validate and use",
    )
    args = parser.parse_args()

    generated = amalgamation(args.manifest.resolve())
    if args.stdout:
        sys.stdout.write(generated)
        return 0
    if args.check:
        check_path = args.check.resolve()
        if not check_path.exists() or check_path.read_text(encoding="utf-8") != generated:
            print("nikki amalgamation is stale; regenerate {}".format(check_path), file=sys.stderr)
            return 1
        return 0

    output_path = args.output.resolve()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(generated, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
