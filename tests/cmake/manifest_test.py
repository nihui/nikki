from pathlib import Path
import subprocess
import sys
import tempfile


PROJECT_ROOT = Path(__file__).resolve().parents[2]
AMALGAMATE = PROJECT_ROOT / "tools" / "amalgamate.py"


def run_manifest(contents):
    with tempfile.TemporaryDirectory() as temporary_directory:
        manifest = Path(temporary_directory) / "source_manifest.txt"
        manifest.write_text(contents, encoding="utf-8")
        return subprocess.run(
            [sys.executable, str(AMALGAMATE), "--stdout", "--manifest", str(manifest)],
            cwd=PROJECT_ROOT,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            check=False,
        )


def expect_failure(contents, message):
    result = run_manifest(contents)
    if result.returncode == 0 or message not in result.stderr:
        raise RuntimeError(
            "manifest validation did not reject {!r}: {}".format(
                contents, result.stderr
            )
        )


def main():
    current = (PROJECT_ROOT / "src" / "source_manifest.txt").read_text(
        encoding="utf-8"
    )
    valid = run_manifest(current)
    if valid.returncode != 0 or not valid.stdout.startswith("// Generated by"):
        raise RuntimeError("current manifest is invalid: " + valid.stderr)

    expect_failure("unknown src/common.h\n", "invalid source manifest entry")
    expect_failure(
        "driver src/common.h\ndriver src/common.h\n",
        "duplicate source manifest path",
    )
    expect_failure("driver src/not-present.cpp\n", "does not exist")
    expect_failure("driver ../outside.cpp\n", "invalid source manifest path")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
